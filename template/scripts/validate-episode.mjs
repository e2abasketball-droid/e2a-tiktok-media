#!/usr/bin/env node
// Validates an episode JSON before rendering. Fails on anything that would produce a broken or
// misleading video; warns on editing choices that hurt retention.
// Usage: node scripts/validate-episode.mjs episodes/<id>.json
import fs from 'node:fs';

const file = process.argv[2];
const ep = JSON.parse(fs.readFileSync(file, 'utf8'));
const errors = [];
const warns = [];
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
const keys = ep.words.map((w) => norm(w.text));
const resolve = (a, off = 0) => {
  if (typeof a === 'number') return a + off;
  const [phrase, occ] = a.split('#');
  const want = occ ? parseInt(occ, 10) - 1 : 0;
  const p = phrase.split(/\s+/).map(norm).filter(Boolean);
  let seen = 0;
  for (let i = 0; i + p.length <= keys.length; i++) {
    if (p.every((w, k) => keys[i + k] === w)) {
      if (seen === want) return ep.words[i].start + off;
      seen++;
    }
  }
  errors.push(`anchor not found in narration: "${a}"`);
  return NaN;
};

for (const k of ['id', 'title', 'style', 'voice', 'words', 'scenes', 'sources']) if (!ep[k]) errors.push(`missing field: ${k}`);
if (!['record', 'player', 'tactical', 'comparison', 'curiosity'].includes(ep.style)) errors.push(`unknown style ${ep.style}`);
if (!ep.sources?.length) errors.push('sources[] is empty: every fact must be checked against a source');
if (ep.words.some((w, i) => i && w.start < ep.words[i - 1].start)) errors.push('word timings are not in order');

const vEnd = ep.words.at(-1).end;
const total = vEnd + 0.25 + (ep.outro?.seconds ?? 1.4);
if (['record', 'curiosity', 'player', 'comparison'].includes(ep.style) && (total < 20 || total > 26))
  warns.push(`duration ${total.toFixed(1)}s is outside the 20-25 s target for ${ep.style}`);
if (ep.words[0].start > 0.4) warns.push('narration starts late: the hook must be heard in the first 0.4 s');

const starts = ep.scenes.map((s, i) => (i === 0 ? 0 : resolve(s.at, s.offset ?? 0)));
starts.forEach((s, i) => {
  if (i && s <= starts[i - 1]) errors.push(`scene ${i} starts before scene ${i - 1}`);
});
ep.scenes.forEach((s, i) => {
  const end = i + 1 < starts.length ? starts[i + 1] : vEnd + 0.25;
  const d = end - starts[i];
  if (s.type !== 'court' && d > 6) warns.push(`scene ${i} (${s.type}) lasts ${d.toFixed(1)} s: split it or add beats/callouts`);
  if (s.camera === 'static' && s.type !== 'court' && d > 2.5) warns.push(`scene ${i} is static for ${d.toFixed(1)} s`);
  if (s.type === 'media') {
    const m = s.media;
    if (!m?.credit || !m?.license) errors.push(`scene ${i}: media needs credit and license`);
    if (!fs.existsSync(new URL(`../public/${m?.src}`, import.meta.url))) errors.push(`scene ${i}: media file missing public/${m?.src}`);
    if (/\bai\b|ai-generated|generated by|higgsfield|midjourney|dall-e/i.test(`${m?.credit} ${m?.license}`) && m?.kind !== 'recreation') errors.push(`scene ${i}: AI imagery must use kind "recreation" so it is labelled on screen`);
  }
  for (const [what, m] of [['bg', s.bg], ['inset', s.inset]]) {
    if (!m) continue;
    if (!m.credit || !m.license) errors.push(`scene ${i}: ${what} needs credit and license`);
    if (!fs.existsSync(new URL(`../public/${m.src}`, import.meta.url))) errors.push(`scene ${i}: ${what} file missing public/${m.src}`);
    if (/\bai\b|ai-generated|generated by|higgsfield|midjourney|dall-e/i.test(`${m.credit} ${m.license}`) && m.kind !== 'recreation') errors.push(`scene ${i}: AI imagery in ${what} must use kind "recreation"`);
  }
  if (s.inset?.at !== undefined) resolve(s.inset.at);
  for (const a of [...(s.beats ?? []), ...(s.callouts ?? []).map((c) => c.at), ...(s.items ?? []).map((x) => x.at)]) resolve(a);
  if (s.second) resolve(s.second.at);
});
const types = ep.scenes.map((s) => s.type);
types.forEach((t, i) => {
  if (i >= 2 && t === types[i - 1] && t === types[i - 2]) warns.push(`three "${t}" scenes in a row (scenes ${i - 2}-${i}): vary the visuals`);
});
// Composition variety: what the viewer actually sees (plate + graphic + placement), not just the type.
const plate = (s) => (s.type === 'media' ? `photo-${s.media.fit ?? 'cover'}` : s.bg ? `photo-${s.bg.treatment ?? 'duotone'}` : s.backdrop ?? (s.type === 'court' ? 'navy' : 'arena'));
const comp = (s) => `${s.type}/${plate(s)}/${s.layout ?? 'center'}${s.inset ? '+inset' : ''}`;
const hasPhoto = (s) => s.type === 'media' || !!s.bg || !!s.inset;
ep.scenes.forEach((s, i) => {
  const prev = ep.scenes[i - 1];
  if (i && comp(s) === comp(prev) && !(s.type === 'media' && s.media.src !== prev.media?.src)) warns.push(`scenes ${i - 1} and ${i} look the same (${comp(s)}): change the plate, layout or scene type`);
});
const anyPhoto = ep.scenes.some(hasPhoto);
let run = 0;
let runStart = 0;
ep.scenes.forEach((s, i) => {
  const end = i + 1 < starts.length ? starts[i + 1] : vEnd + 0.25;
  if (hasPhoto(s) || s.type === 'court') run = 0;
  else {
    if (!run) runStart = starts[i];
    run++;
    if (anyPhoto && end - runStart > 6) warns.push(`scenes up to ${i}: ${(end - runStart).toFixed(1)} s of text on a dark backdrop in a row: put a photo plate (bg) or inset in one of them`);
  }
});
// Hook: the first 2 s must show an image and change at least once.
if (anyPhoto && !hasPhoto(ep.scenes[0])) warns.push('scene 0 has no real image: open on a photo (media or bg) so the first frame is a picture, not text on navy');
const firstChange = Math.min(starts[1] ?? 99, ...((ep.scenes[0].second ? [resolve(ep.scenes[0].second.at)] : [])), ...(ep.scenes[0].callouts ?? []).map((c) => resolve(c.at)), ...(ep.scenes[0].beats ?? []).map((b) => resolve(b)));
if (firstChange > 2.0) warns.push(`the hook holds one image for ${firstChange.toFixed(1)} s: add a second figure, callout, beat or cut before 2 s`);
if (ep.scenes.length < Math.floor(vEnd / 4.5)) warns.push(`only ${ep.scenes.length} scenes for ${vEnd.toFixed(0)} s of narration: aim for a new visual every 2-4 s`);
if (!ep.scenes.some((s) => s.type === 'media')) warns.push('no real photo/footage scenes: add licensed media when it exists for this story');

// ---------------------------------------------------------------- v5: hooks, endings, social, rhythm, sound
const HOOKS = {'stat-slam': ['stat'], 'photo-line': ['media', 'headline'], split: ['split'], clock: ['scoreboard', 'stat']};
const hook = ep.hook ?? 'stat-slam';
if (!HOOKS[hook]) errors.push(`unknown hook "${hook}" (stat-slam, photo-line, split, clock)`);
else if (!HOOKS[hook].includes(ep.scenes[0].type)) warns.push(`hook "${hook}" expects scene 0 to be ${HOOKS[hook].join(' or ')}, not ${ep.scenes[0].type}`);
if (hook === 'photo-line' && ep.scenes[0].type === 'headline' && !ep.scenes[0].bg) warns.push('hook "photo-line" needs a photo: give scene 0 a bg');
let hist = [];
try {
  hist = JSON.parse(fs.readFileSync(new URL('../../music/history.json', import.meta.url), 'utf8')).filter((h) => h.episode && h.episode !== ep.id);
} catch {}
const last = (k, n) => hist.slice(-n).map((h) => h[k]).filter(Boolean);
if (last('hook', 2).length === 2 && last('hook', 2).every((h) => h === hook)) warns.push(`hook "${hook}" was also used by the last 2 videos: pick another opening`);
const ENDINGS = ['debate', 'surprise', 'fact', 'emotion'];
if (!ep.ending) warns.push('no "ending" type (debate, surprise, fact, emotion): set it so endings rotate');
else if (!ENDINGS.includes(ep.ending)) errors.push(`unknown ending "${ep.ending}"`);
else {
  if (ep.ending === 'debate' && last('ending', 2).includes('debate')) warns.push('debate ending again within 3 videos: aim for about 1 in 3; use surprise, fact or emotion');
  if (last('ending', 2).length === 2 && last('ending', 2).every((e) => e === ep.ending)) warns.push(`"${ep.ending}" ending three times in a row: vary it`);
}
const BAIT = /comment below|what do you think|agree or disagree|let me know|drop a comment|tag a friend|smash|like and follow|follow for more/i;
if (!ep.social?.caption) warns.push('no social.caption: write the short public caption (English)');
if (!ep.social?.pinnedComment) warns.push('no social.pinnedComment: write a comment to pin that opens a real basketball debate');
for (const [k, v] of Object.entries(ep.social ?? {})) if (typeof v === 'string' && BAIT.test(v)) errors.push(`social.${k} reads as engagement bait ("${v.match(BAIT)[0]}"): rewrite it as a genuine basketball point`);
const tail = ep.words.slice(-12).map((w) => w.text).join(' ');
if (BAIT.test(tail)) errors.push('the narration ends with engagement bait: end on the story, not on a request for comments');
// rhythm: something must change at least every 3 s (cut, beat, callout, second figure, inset, score change)
ep.scenes.forEach((s, i) => {
  const end = i + 1 < starts.length ? starts[i + 1] : vEnd + 0.25;
  if (s.type === 'court' || s.type === 'timeline') return; // they animate continuously
  const ev = [starts[i], end, ...(s.beats ?? []).map((b) => resolve(b)), ...(s.callouts ?? []).map((c) => resolve(c.at))];
  if (s.second) ev.push(resolve(s.second.at));
  if (s.inset?.at !== undefined) ev.push(resolve(s.inset.at));
  if (s.type === 'scoreboard') [s.home, s.away].forEach((t) => t.score.slice(1).forEach(([a]) => ev.push(resolve(a))));
  ev.sort((a, b) => a - b);
  const gap = Math.max(...ev.slice(1).map((x, k) => x - ev[k]));
  if (gap > 3.2) warns.push(`scene ${i} (${s.type}) holds the same picture for ${gap.toFixed(1)} s: add a beat, callout or inset, or cut`);
});
const own = ep.scenes.reduce((n, s) => n + (s.sfx?.length ?? 0) + (s.sfxTransition ? 1 : 0), 0);
if (own > 4) warns.push(`${own} hand-placed sound effects: keep 2-4 highlights per Reel, the music carries the rest`);

warns.forEach((w) => console.warn('WARN  ' + w));
errors.forEach((e) => console.error('ERROR ' + e));
if (errors.length) process.exit(1);
console.log(`episode OK: ${ep.scenes.length} scenes, ${total.toFixed(1)} s`);
